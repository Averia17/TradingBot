package main

import (
	"context"
	"crypto/rand"
	"flag"
	"log/slog"
	"os"
	"os/signal"
	"syscall"
	"time"

	"tradingbot/control/internal/researchworker"
)

func main() {
	var cfg researchworker.Config
	flag.StringVar(&cfg.BaseURL, "control-url", "http://127.0.0.1:8080", "research control API base URL")
	flag.StringVar(&cfg.WorkerID, "worker-id", "", "worker identity (generated by default)")
	flag.DurationVar(&cfg.PollInterval, "poll-interval", time.Second, "delay after an empty queue or transient error")
	flag.DurationVar(&cfg.HeartbeatInterval, "heartbeat-interval", 10*time.Second, "maximum interval between heartbeats")
	flag.DurationVar(&cfg.RequestTimeout, "request-timeout", 5*time.Second, "timeout per control HTTP request")
	flag.Parse()
	if cfg.WorkerID == "" {
		cfg.WorkerID = "research-fixture-" + rand.Text()
	}
	ctx, stop := signal.NotifyContext(context.Background(), os.Interrupt, syscall.SIGTERM)
	defer stop()
	if err := researchworker.Run(ctx, cfg, researchworker.AnalyzeSynthetic); err != nil {
		slog.Error("research fixture worker stopped", "error", err)
		os.Exit(1)
	}
}
